// Code point sets of the Unicode properties jsfix.js expands in regular expressions (\p{L}, \p{Script=Arabic},
// \p{Extended_Pictographic}...), taken from the host engine's own \p{} support. Ranges are delta-encoded in base 36
// ("start-length" pairs, starts relative to the previous end).
// In CI:  node tools/gen-unicode.js > Resources/js/unicode-props.js   (the app loads it next to jsfix.js)
// In a desktop browser page it defines window.JSFIX_UNICODE directly (the test pages).
(function (root) {
    var PROPS = ['L', 'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'M', 'Mn', 'Mc', 'Me', 'N', 'Nd', 'Nl', 'No', 'P', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po',
        'S', 'Sm', 'Sc', 'Sk', 'So', 'Z', 'Zs', 'Zl', 'Zp', 'Cc', 'Cf', 'Co', 'Alphabetic', 'White_Space', 'Emoji', 'Emoji_Presentation',
        'Emoji_Modifier', 'Emoji_Modifier_Base', 'Emoji_Component', 'Extended_Pictographic', 'Uppercase', 'Lowercase', 'ID_Start', 'ID_Continue',
        'Diacritic', 'Ideographic', 'Regional_Indicator', 'ASCII', 'Any', 'Assigned', 'Script=Latin', 'Script=Greek', 'Script=Cyrillic',
        'Script=Armenian', 'Script=Hebrew', 'Script=Arabic', 'Script=Devanagari', 'Script=Bengali', 'Script=Thai', 'Script=Georgian',
        'Script=Hangul', 'Script=Hiragana', 'Script=Katakana', 'Script=Han', 'Script=Common', 'Script=Inherited',
        // (more that libraries use: FormatJS's message parser [^\p{White_Space}\p{Pattern_Syntax}], CJK tests with
        // Bopomofo - one unknown property and the whole pattern failed, kosik.cz stopped at its loader)
        'C', 'Cn', 'Cs', 'LC', 'Pattern_Syntax', 'Pattern_White_Space', 'XID_Start', 'XID_Continue', 'Dash', 'Hex_Digit', 'ASCII_Hex_Digit',
        'Math', 'Quotation_Mark', 'Terminal_Punctuation', 'Sentence_Terminal', 'Variation_Selector', 'Default_Ignorable_Code_Point', 'Cased',
        'Case_Ignorable', 'Join_Control', 'Extender', 'Grapheme_Extend', 'Unified_Ideograph',
        'Script=Bopomofo', 'Script=Tamil', 'Script=Telugu', 'Script=Kannada', 'Script=Malayalam', 'Script=Gujarati', 'Script=Gurmukhi',
        'Script=Oriya', 'Script=Sinhala', 'Script=Khmer', 'Script=Lao', 'Script=Myanmar', 'Script=Tibetan', 'Script=Ethiopic',
        'Script=Mongolian', 'Script=Syriac', 'Script=Thaana'];
    var build = function () {
        var tables = {};
        for (var k = 0; k < PROPS.length; k++) {
            var re = new RegExp('^\\p{' + PROPS[k] + '}$', 'u'), parts = [], prev = 0, start = -1;
            for (var cp = 0; cp <= 0x110000; cp++) {
                if (cp === 0xD800) cp = 0xE000;   // (surrogates are not characters)
                var m = cp <= 0x10FFFF && re.test(String.fromCodePoint(cp));
                if (m && start < 0) start = cp;
                if (!m && start >= 0) {
                    var end = cp - 1;
                    parts.push((start - prev).toString(36) + (end > start ? '-' + (end - start).toString(36) : ''));
                    prev = end;
                    start = -1;
                }
            }
            tables[PROPS[k]] = parts.join(',');
        }
        return tables;
    };
    if (typeof module !== 'undefined' && module.exports && typeof require !== 'undefined') {
        if (require.main === module) {
            process.stdout.write('// generated by tools/gen-unicode.js from node ' + process.version + ' (Unicode ' + process.versions.unicode + ')\n' +
                                 'var JSFIX_UNICODE = ' + JSON.stringify(build()) + ';\n');
        } else module.exports = build;   // (tools/jsfix-ci.js)
    } else if (root) root.JSFIX_UNICODE = build();
})(typeof window !== 'undefined' ? window : this);
