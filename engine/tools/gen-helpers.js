// Prints the transpiler's runtime helpers (Resources/jsfix.js) as one script of global function declarations, which
// the app puts into the polyfill bundle (Resources/js/jsfix-helpers.js): lowered code that a page keeps as text and
// runs later with new Function or eval (MediaWiki keeps its modules in localStorage) no longer sees the helpers of the
// script it came from ("Can't find variable: __br_spread" on Wikipedia).
// Usage (CI): node tools/gen-helpers.js > Resources/js/jsfix-helpers.js   (needs the acorn package)
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ctx = vm.createContext({ acorn: require('acorn') });
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'Resources', 'jsfix.js'), 'utf8'), ctx, { filename: 'jsfix.js' });
const text = ctx.JSFix.helperSource();
if (!/^function __br_spread/m.test(text)) { console.error('gen-helpers: no helpers found'); process.exit(1); }
process.stdout.write('/* jsfix.js runtime helpers, generated by tools/gen-helpers.js */\n' + text);
